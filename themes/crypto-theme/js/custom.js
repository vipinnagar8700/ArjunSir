// make sticky js 

window.addEventListener('scroll', function() {
  var scrollPosition = window.scrollY;
  var stickyDivs = document.querySelectorAll('.myStickyDiv');

  stickyDivs.forEach(function(stickyDiv) {
      // Change '100' to the scroll position where you want the class to be added
      if (scrollPosition > 100) {
          stickyDiv.classList.add('scrolled');
      } else {
          stickyDiv.classList.remove('scrolled');
      }
  });
});












